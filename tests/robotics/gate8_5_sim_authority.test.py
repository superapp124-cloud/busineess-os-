class TestRobotModelIntegrity:
    """Phase 8.5-A: CHATR-H170 loads correctly from JSON profiles."""

    def test_profile_directory_exists(self):
        """chatr_h170/ profile directory must exist and contain all required files."""
        assert PROFILE_DIR.exists(), f"Profile dir missing: {PROFILE_DIR}"
        required = ["robot.json", "joints.json", "links.json", "actuators.json", "sensors.json"]
        for f in required:
            assert (PROFILE_DIR / f).exists(), f"Missing profile file: {f}"

    def test_robot_json_canonical_values(self):
        """robot.json must declare: 68kg, 28 DOF, 29 links, 1.75m height."""
        robot = json.loads((PROFILE_DIR / "robot.json").read_text())
        assert robot["totalMassKg"] == 68.0, f"Mass mismatch: {robot['totalMassKg']} != 68.0"
        assert robot["dofCount"] == 28,      f"DOF mismatch: {robot['dofCount']} != 28"
        assert robot["heightMeters"] == 1.75, f"Height mismatch: {robot['heightMeters']}"
        assert robot["baseLink"] == "pelvis"

    def test_joints_json_exactly_28(self):
        """joints.json must define exactly 28 revolute joints."""
        joints = json.loads((PROFILE_DIR / "joints.json").read_text())
        assert len(joints) == 28, f"Expected 28 joints, got {len(joints)}"
        for j in joints:
            assert j["type"] == "revolute", f"Non-revolute joint: {j['id']}"

    def test_links_json_exactly_29(self):
        """links.json must define exactly 29 rigid links."""
        links = json.loads((PROFILE_DIR / "links.json").read_text())
        assert len(links) == 29, f"Expected 29 links, got {len(links)}"

    def test_joint_limits_physically_valid(self):
        """All joint limits must be finite and minRad < maxRad."""
        joints = json.loads((PROFILE_DIR / "joints.json").read_text())
        for j in joints:
            lim = j["limits"]
            assert lim["minRad"] < lim["maxRad"], \
                f"{j['id']}: minRad >= maxRad ({lim['minRad']} >= {lim['maxRad']})"
            assert lim["maxTorqueNm"] > 0, f"{j['id']}: maxTorqueNm must be > 0"
            assert math.isfinite(lim["minRad"]) and math.isfinite(lim["maxRad"]), \
                f"{j['id']}: non-finite joint limits"

    def test_link_inertias_positive_definite(self):
        """All link inertia diagonal terms must be positive."""
        links = json.loads((PROFILE_DIR / "links.json").read_text())
        for l in links:
            I = l["inertia"]
            assert I["ixx"] > 0, f"{l['id']}: ixx <= 0"
            assert I["iyy"] > 0, f"{l['id']}: iyy <= 0"
            assert I["izz"] > 0, f"{l['id']}: izz <= 0"

    def test_total_link_mass_matches_robot_json(self):
        """Sum of link masses must equal robot.json totalMassKg within 5%."""
        robot = json.loads((PROFILE_DIR / "robot.json").read_text())
        links = json.loads((PROFILE_DIR / "links.json").read_text())
        total = sum(l["massKg"] for l in links)
        expected = robot["totalMassKg"]
        assert abs(total - expected) / expected < 0.05, \
            f"Mass sum {total:.2f} kg differs from declared {expected} kg by > 5%"

    def test_mjcf_model_exists(self):
        """chatr_h170.xml must exist (generated by build_mjcf.py)."""
        assert MODEL_PATH.exists(), \
            f"MJCF not found: {MODEL_PATH}\nRun: python sim-server/compiler/build_mjcf.py"

    @requires_mujoco
    def test_mjcf_loads_in_mujoco(self):
        """MuJoCo must accept chatr_h170.xml without errors."""
        model = mujoco.MjModel.from_xml_path(str(MODEL_PATH))
        assert model is not None
        assert model.nbody > 0

    @requires_mujoco
    def test_canonical_dof_invariants(self):
        """
        Explicit invariant verification:
          - Canonical actuated DOF = 28
          - MuJoCo scalar actuators (nu) = 28
          - MuJoCo root free joint = 1
          - MuJoCo total joints (njnt) = 29 (28 revolute + 1 freejoint)
          - MuJoCo generalized coordinates (nq) = 35 (28 + 7 freejoint [3 pos + 4 quat])
          - MuJoCo generalized velocities (nv) = 34 (28 + 6 freejoint [3 lin + 3 ang])
          - Robot links = 29
          - MuJoCo total bodies = 30 (29 links + 1 worldbody)
        """
        robot = json.loads((PROFILE_DIR / "robot.json").read_text())
        joints = json.loads((PROFILE_DIR / "joints.json").read_text())
        links = json.loads((PROFILE_DIR / "links.json").read_text())
        model = mujoco.MjModel.from_xml_path(str(MODEL_PATH))

        assert robot["dofCount"] == 28
        assert len(joints) == 28
        assert len(links) == 29

        assert model.nu == 28, f"MuJoCo nu={model.nu} != 28"
        assert model.njnt == 29, f"MuJoCo njnt={model.njnt} != 29 (28 revolute + 1 root)"
        assert model.nq == 35, f"MuJoCo nq={model.nq} != 35 (28 + 7)"
        assert model.nv == 34, f"MuJoCo nv={model.nv} != 34 (28 + 6)"
        assert model.nbody == 30, f"MuJoCo nbody={model.nbody} != 30 (29 links + 1 world)"



