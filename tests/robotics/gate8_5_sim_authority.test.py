class TestCrossValidator:
    """Phase 8.5-G: Reference vs simulator joint position cross-validation."""

    def test_identical_states_have_zero_divergence(self):
        """When reference == sim, all divergences must be 0%."""
        import sys; sys.path.insert(0, str(REPO_ROOT / "packages" / "robot-physics" / "src" / "crossValidation"))
        # Use standalone validator module
        from cross_validator_standalone import CrossValidator

        reference = {"neck_yaw": 0.0, "neck_pitch": 0.0, "l_hip_pitch": -0.2}
        sim_states = {"neck_yaw": {"posRad": 0.0}, "neck_pitch": {"posRad": 0.0}, "l_hip_pitch": {"posRad": -0.2}}
        result = CrossValidator.validate_standalone(reference, sim_states)
        assert result["is_valid"] is True
