// ============================================================
// SOUP TRAINING CLIENT
// ============================================================

export class SoupTrainingClient {
  private endpoint: string;

  constructor(endpoint = 'http://localhost:8000') {
    this.endpoint = endpoint.replace(/\/$/, '');
  }

  setEndpoint(url: string): void {
    this.endpoint = url.replace(/\/$/, '');
  }

  /** Check training worker health. */
  async healthCheck(): Promise<TrainingWorkerHealth> {
    try {
      const res = await fetch(`${this.endpoint}/training-health`, {
        signal: AbortSignal.timeout(5000),
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (err: any) {
      return {
        status: 'OFFLINE',
        gpuName: 'Unknown',
        vramTotalGb: 0,
        vramFreeGb: 0,
        backend: 'COLAB_T4',
      };
    }
  }

  /**
   * Submit a training job to the Soup worker.
   * The dataset is sent as base64 — the worker writes it to /content/chatr_datasets/.
   * The locked soup.yaml is generated by the Python SoupJobController on the Dell;
   * this client just transmits the approved plan + encoded data.
   */
  async submitTrainingJob(
    plan: TrainingJobPlan,
    datasetB64: string,
    evalDatasetB64?: string,
    configB64?: string,
    policyHash?: string
  ): Promise<{ jobId: string; state: string }> {
    const res = await fetch(`${this.endpoint}/train`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        capability: plan.capability,
        base_model: plan.baseModel,
        method: plan.method,
        dataset_id: plan.datasetId,
        dataset_b64: datasetB64,
        eval_b64: evalDatasetB64 ?? '',
        config_b64: configB64 ?? '',
        policy_hash: policyHash ?? '',
        lora_rank: plan.loraRank ?? 16,
        lora_alpha: plan.loraAlpha ?? 32,
        max_seq_len: plan.maxSeqLen ?? 1024,
        batch_size: plan.batchSize ?? 4,
        seed: plan.seed ?? 1234,
      }),
    });
    if (!res.ok) throw new Error(`Training submission failed: HTTP ${res.status}`);
    return res.json();
  }

  /** Poll training job status. */
  async getTrainingStatus(jobId: string): Promise<TrainingJobStatus> {
    const res = await fetch(`${this.endpoint}/train-status/${jobId}`, {
      signal: AbortSignal.timeout(10000),
    });
    if (!res.ok) throw new Error(`Status check failed: HTTP ${res.status}`);
    return res.json();
  }

  /** Get Soup's `soup ship` verdict for a completed training job. */
  async getShipVerdict(jobId: string): Promise<SoupShipVerdict> {
    const res = await fetch(`${this.endpoint}/ship-verdict/${jobId}`, {
      signal: AbortSignal.timeout(15000),
    });
    if (!res.ok) throw new Error(`Ship verdict failed: HTTP ${res.status}`);
    return res.json();
  }

  /** Download the trained adapter as a Blob (.safetensors zip). */
  async downloadAdapter(jobId: string): Promise<Blob> {
    const res = await fetch(`${this.endpoint}/download-adapter/${jobId}`, {
      signal: AbortSignal.timeout(120000),
    });
    if (!res.ok) throw new Error(`Adapter download failed: HTTP ${res.status}`);
    return res.blob();
  }

  /** Cancel a running training job. */
  async cancelJob(jobId: string): Promise<{ success: boolean }> {
    const res = await fetch(`${this.endpoint}/cancel-job/${jobId}`, {
      method: 'POST',
      signal: AbortSignal.timeout(10000),
    });
    if (!res.ok) return { success: false };
    return res.json();
  }

  /** Get training logs tail for a job. */
  async getTrainingLogs(jobId: string, tailLines = 50): Promise<string[]> {
    const res = await fetch(`${this.endpoint}/train-logs/${jobId}?tail=${tailLines}`, {
      signal: AbortSignal.timeout(10000),
    });
    if (!res.ok) return [];
    const data = await res.json();
    return data.lines ?? [];
  }
}
