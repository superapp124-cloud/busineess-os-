/**
 * CHATR AI Training Infrastructure
 * src/services/ai/SoupTrainingClient.ts
 *
 * Dedicated TypeScript client for the Soup training worker running on Colab/Kaggle T4.
 * This is SEPARATE from VideoGenerationWorker.ts (different concerns, different endpoints).
 *
 * Training worker runs alongside the video worker on the same Colab notebook,
 * but uses completely independent FastAPI routes.
 */

export type TrainingMethod = 'sft' | 'dpo' | 'orpo';
export type SoupShipVerdictResult = 'SHIP' | 'DONT_SHIP' | 'UNKNOWN';

export type ChatrCapability =
  | 'general' | 'coding' | 'reasoning' | 'business' | 'finance'
  | 'seo' | 'marketing' | 'creator' | 'video' | 'research'
  | 'support' | 'agent' | 'rag' | 'meera';

// ============================================================
// REQUEST / RESPONSE TYPES
// ============================================================

